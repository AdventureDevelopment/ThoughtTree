#!/usr/bin/env bash
# Assembles the on-device site of spike 2 (no computer needed on the phone): the AOT build under /aot/, the device
# runner at /aot/spike/device.html, a start page at /, build-info.json with the git commit, and a
# staticwebapp.config.json with a strict Content-Security-Policy for this site only (as spike 1: own origin,
# 'wasm-unsafe-eval' and the hash of the build's inline import map; no unsafe-inline).
# Usage: harness/publish-device.sh [output-folder]   (default publish/device-site; runs harness/publish.sh first)
set -euo pipefail
cd "$(dirname "$0")/.."
out="${1:-publish/device-site}"
[ -f publish/aot/wwwroot/index.html ] || harness/publish.sh aot
rm -rf "$out"; mkdir -p "$out"
commit=$(git rev-parse HEAD)$(git diff --quiet -- . || echo "+dirty")
cp -r publish/aot/wwwroot "$out/aot"
sed -i 's#<base href="/" />#<base href="/aot/" />#' "$out/aot/index.html"
rm -f "$out/aot/index.html.br" "$out/aot/index.html.gz"   # stale precompressed copies of the changed page
printf '{ "gitCommit": "%s", "build": "aot" }\n' "$commit" > "$out/aot/spike/build-info.json"
cat > "$out/index.html" <<'HTML'
<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta http-equiv="refresh" content="0; url=aot/spike/device.html" /><title>Spike 2</title></head>
<body><p><a href="aot/spike/device.html">Spike 2 device runner</a></p></body></html>
HTML
python3 - "$out" <<'PY'
import base64, hashlib, json, pathlib, re, sys
site = pathlib.Path(sys.argv[1])
page = (site / "aot" / "index.html").read_text(encoding="utf-8")
maps = re.findall(r'<script type="importmap">(.*?)</script>', page, re.S)
inline = [m for m in re.findall(r"<script(?![^>]*\ssrc=)[^>]*>", page) if 'type="importmap"' not in m]
if len(maps) != 1 or inline: sys.exit("aot/index.html: expected one import map and no other inline script")
digest = "'sha256-" + base64.b64encode(hashlib.sha256(maps[0].encode("utf-8")).digest()).decode() + "'"
for html in site.rglob("*.html"):
    text = html.read_text(encoding="utf-8")
    if re.search(r"<script(?![^>]*\ssrc=)(?![^>]*importmap)[^>]*>|\son[a-z]+=|\sstyle=", text): sys.exit(f"{html}: inline script, handler or style")
csp = ("default-src 'self'; script-src 'self' 'wasm-unsafe-eval' " + digest + "; style-src 'self'; img-src 'self'; font-src 'self'; "
       "connect-src 'self'; manifest-src 'self'; worker-src 'self'; media-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'")
config = {"$comment": "Spike 2 device site only (generated by spikes/spike-2/harness/publish-device.sh); not the app's policy.",
          "globalHeaders": {"Content-Security-Policy": csp, "Referrer-Policy": "no-referrer", "X-Content-Type-Options": "nosniff"},
          "routes": [{"route": "/.auth/login/github", "statusCode": 404}, {"route": "/.auth/login/aad", "statusCode": 404}],
          "mimeTypes": {".wasm": "application/wasm", ".dat": "application/octet-stream", ".json": "application/json"}}
(site / "staticwebapp.config.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
print("CSP:", csp)
PY
du -sh "$out" | sed 's#^#  #'
echo "Serve locally: node ../spike-1/harness/server.mjs --port 5280 --root $out --headers $out/staticwebapp.config.json"
