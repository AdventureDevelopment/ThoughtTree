#!/usr/bin/env bash
# Assembles the on-device spike site (no computer needed on the phone): both builds under /interpreted/ and /aot/ of
# one origin (they share the IndexedDB datasets), the device runner at /interpreted/spike/device.html, a start page at
# /, the dataset manifest (the page generates the datasets itself), build-info.json with the git commit, and a
# staticwebapp.config.json with a strict Content-Security-Policy for this site only (ADR-045 style: own origin,
# 'wasm-unsafe-eval' and the hashes of the two builds' inline import maps; no unsafe-inline).
# Usage: harness/publish-device.sh [output-folder]   (default publish/device-site; runs harness/publish.sh first)
set -euo pipefail
cd "$(dirname "$0")/.."
out="${1:-publish/device-site}"
[ -f publish/interpreted/wwwroot/index.html ] && [ -f publish/aot/wwwroot/index.html ] || harness/publish.sh
rm -rf "$out"; mkdir -p "$out"
commit=$(git rev-parse HEAD)$(git diff --quiet -- . || echo "+dirty")
for build in interpreted aot; do
  cp -r "publish/$build/wwwroot" "$out/$build"
  sed -i "s#<base href=\"/\" />#<base href=\"/$build/\" />#" "$out/$build/index.html"
  cp ../../docs/spikes/spike-1/data/manifest.json "$out/$build/spike/manifest.json"
  printf '{ "gitCommit": "%s", "build": "%s" }\n' "$commit" "$build" > "$out/$build/spike/build-info.json"
  rm -f "$out/$build/spike/durability.html" "$out/$build/spike/contract.html"   # desktop-only pages with inline scripts
done
cat > "$out/index.html" <<'HTML'
<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta http-equiv="refresh" content="0; url=interpreted/spike/device.html" /><title>Spike 1</title></head>
<body><p><a href="interpreted/spike/device.html">Spike 1 device runner</a></p></body></html>
HTML
python3 - "$out" <<'PY'
import base64, hashlib, json, pathlib, re, sys
site = pathlib.Path(sys.argv[1])
hashes = []
for build in ("interpreted", "aot"):
    page = (site / build / "index.html").read_text(encoding="utf-8")
    maps = re.findall(r'<script type="importmap">(.*?)</script>', page, re.S)
    inline = [m for m in re.findall(r"<script(?![^>]*\ssrc=)[^>]*>", page) if 'type="importmap"' not in m]
    if len(maps) != 1 or inline: sys.exit(f"{build}/index.html: expected one import map and no other inline script")
    hashes.append("'sha256-" + base64.b64encode(hashlib.sha256(maps[0].encode("utf-8")).digest()).decode() + "'")
for html in site.rglob("*.html"):
    text = html.read_text(encoding="utf-8")
    if re.search(r"<script(?![^>]*\ssrc=)(?![^>]*importmap)[^>]*>|\son[a-z]+=|\sstyle=", text): sys.exit(f"{html}: inline script, handler or style")
csp = ("default-src 'self'; script-src 'self' 'wasm-unsafe-eval' " + " ".join(hashes) + "; style-src 'self'; img-src 'self'; font-src 'self'; "
       "connect-src 'self'; manifest-src 'self'; worker-src 'self'; media-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'")
config = {"$comment": "Spike 1 device site only (generated by spikes/spike-1/harness/publish-device.sh); not the app's policy.",
          "globalHeaders": {"Content-Security-Policy": csp, "Referrer-Policy": "no-referrer", "X-Content-Type-Options": "nosniff"},
          # Same as the app's config: switch off the sign-in providers Static Web Apps enables on every site
          # (eng/deploy/check-headers.sh requires 404 there).
          "routes": [{"route": "/.auth/login/github", "statusCode": 404}, {"route": "/.auth/login/aad", "statusCode": 404}],
          "mimeTypes": {".wasm": "application/wasm", ".dat": "application/octet-stream", ".json": "application/json"}}
(site / "staticwebapp.config.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
print("CSP:", csp)
PY
du -sh "$out" "$out"/interpreted "$out"/aot | sed 's#^#  #'
echo "Serve locally: node harness/server.mjs --port 5080 --root $out --headers $out/staticwebapp.config.json"
