using ThoughtTree.Architecture.Rules.Support;
using static ArchUnitNET.Fluent.ArchRuleDefinition;
using static ThoughtTree.Architecture.Rules.Support.DependencyConditions;
using static ThoughtTree.Architecture.Rules.Support.SourceArchitecture;
using static ThoughtTree.Architecture.Rules.Support.SourceProjects;

namespace ThoughtTree.Architecture.Rules.Dependencies;

/// <summary>Type-level dependency and namespace rules over the compiled source assemblies (ArchUnitNET).</summary>
[Trait("Intent", "Secure")]
public class TypeDependencyRules
{
    private const string BrowserInterop = @"^(Microsoft\.JSInterop|System\.Runtime\.InteropServices\.JavaScript)\.";
    private const string AspNetCore = @"^Microsoft\.AspNetCore\.";
    private const string DomainTypes = @"^ThoughtTree\.Domain\.";

    [Fact]
    [Trait("ADR", "ADR-054")]
    public void All_six_source_assemblies_are_loaded()
    {
        Instance.Assemblies.Select(a => a.Name.Split(',')[0]).Order(StringComparer.Ordinal)
            .ShouldBe(All.Order(StringComparer.Ordinal));
    }

    [Theory]
    [Trait("ADR", "ADR-054")]
    [MemberData(nameof(SourceNames))]
    public void Every_type_lives_in_the_namespace_of_its_project(string project)
    {
        // Composition roots (Program, top-level statements) and types generated by the compiler or by
        // source generators of the SDK (embedded attributes) are the only exceptions.
        var otherProjects = string.Join('|', All.Where(p => p != project && !project.StartsWith(p + ".", StringComparison.Ordinal)).Select(Escape));
        Types().That().ResideInAssembly(Load(project))
            .And().DoNotHaveFullNameMatching(@"^(Program|<.*|Microsoft\.CodeAnalysis\..*|System\.Runtime\.CompilerServices\..*|Microsoft\.Extensions\.[A-Za-z.]*\.Embedded\..*)")
            .Should().ResideInNamespaceMatching($@"^{Escape(project)}(\..*)?$")
            .AndShould().NotResideInNamespaceMatching($@"^({otherProjects})(\..*)?$")
            .Because("ADR-054: layers and features are separated by namespace inside each project")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Theory]
    [Trait("ADR", "ADR-027")]
    [InlineData(ServerProject)]
    [InlineData(ServerCoreProject)]
    public void Server_types_do_not_use_domain(string project)
    {
        Types().That().ResideInAssembly(Load(project))
            .Should().FollowCustomCondition(UsesNoTypeMatching(DomainTypes), "not use Domain")
            .Because("ADR-027: the server shares only Contracts with the client")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-053")]
    [Trait("ADR", "ADR-027")]
    public void Domain_types_depend_on_nothing_outside_domain()
    {
        const string forbidden =
            @"^(ThoughtTree\.(?!Domain\.)|Microsoft\.AspNetCore\.|Microsoft\.JSInterop\.|System\.Runtime\.InteropServices\.JavaScript\.|System\.Net\.|System\.IO\.)"
            + @"|^(System\.Threading\.Tasks\.(Task|ValueTask)(`1)?|System\.Collections\.Generic\.IAsyncEnumerable`1|System\.Console|System\.Environment)$";

        Types().That().ResideInAssembly(Load(DomainProject))
            .Should().FollowCustomCondition(UsesNoTypeMatching(forbidden), "depend on nothing outside Domain and the pure base library")
            .Because("ADR-053: Domain depends on nothing; ADR-027: no browser, interop, storage, network or async I/O")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-053")]
    [Trait("ADR", "ADR-041")]
    public void Client_application_layer_uses_neither_ui_nor_browser()
    {
        const string forbidden =
            @"^(ThoughtTree\.Client\.(?!App\.)|ThoughtTree\.Server\.|Microsoft\.AspNetCore\.|Microsoft\.JSInterop\.|System\.Runtime\.InteropServices\.JavaScript\.)";

        Types().That().ResideInAssembly(Load(ClientAppProject))
            .Should().FollowCustomCondition(UsesNoTypeMatching(forbidden), "use neither UI, server nor browser")
            .Because("ADR-053: dependencies point inwards; ADR-041: Client.App is plain C# without Razor or browser dependencies")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-053")]
    public void Client_never_uses_domain()
    {
        Types().That().ResideInAssembly(Load(ClientProject))
            .Should().FollowCustomCondition(UsesNoTypeMatching(DomainTypes), "not use Domain")
            .Because("ADR-053: the UI binds only to view models of the application layer")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-053")]
    [Trait("ADR", "ADR-054")]
    public void Ui_uses_neither_adapters_nor_contracts()
    {
        Types().That().ResideInAssembly(Load(ClientProject))
            .And().DoNotResideInNamespaceOrBelow(ClientAdapters)
            .And().DoNotHaveFullNameMatching(@"^Program(\W.*)?$")
            .Should().FollowCustomCondition(UsesNoTypeMatching(@"^(ThoughtTree\.Client\.Adapters|ThoughtTree\.Contracts)\."), "use neither adapters nor Contracts")
            .Because("ADR-053: the UI references Application only; ADR-054: UI does not use browser adapters directly (the composition root wires them)")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-042")]
    public void Javascript_interop_only_in_the_adapters_namespace()
    {
        Types().That().ResideInAssembly(Load(ClientProject)).And().DoNotResideInNamespaceOrBelow(ClientAdapters)
            .Should().FollowCustomCondition(UsesNoTypeMatching(BrowserInterop), "not use JavaScript interop")
            .Because($"ADR-042: IJSRuntime and JavaScript interop only in {ClientAdapters}")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-042")]
    [Trait("ADR", "ADR-027")]
    public void Javascript_interop_not_outside_the_client()
    {
        Types().That().ResideInAssembly(Load(DomainProject), Load(ContractsProject), Load(ClientAppProject), Load(ServerCoreProject), Load(ServerProject))
            .Should().FollowCustomCondition(UsesNoTypeMatching(BrowserInterop), "not use JavaScript interop")
            .Because("ADR-042: every browser API is reached through a C# interface implemented in the client adapters")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-040")]
    public void Server_core_does_not_use_aspnet_core()
    {
        Types().That().ResideInAssembly(Load(ServerCoreProject))
            .Should().FollowCustomCondition(UsesNoTypeMatching(AspNetCore), "not use ASP.NET Core")
            .Because("ADR-040: the simulation uses the real server logic directly, without HTTP")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    [Fact]
    [Trait("ADR", "ADR-054")]
    public void Endpoints_do_not_use_stores_directly()
    {
        Types().That().ResideInNamespaceOrBelow(ServerEndpoints)
            .Should().FollowCustomCondition(UsesNoTypeMatching($@"^{Escape(ServerStores)}\."), "not use stores")
            .Because("ADR-054: endpoints go through Server.Core ports, not through stores")
            .WithoutRequiringPositiveResults()
            .ShouldHold();
    }

    public static TheoryData<string> SourceNames() => [.. All];

    private static string Escape(string name) => name.Replace(".", @"\.", StringComparison.Ordinal);
}
